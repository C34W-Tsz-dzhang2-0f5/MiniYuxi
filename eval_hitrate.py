# 反向验证用：把前 5 条换成与 HR 制度无关的问句（期望关键词在语料中不存在）
NOISE_QA = [
    ("今天天气怎么样？", ["台风橙色预警"]),
    ("如何在家做蛋糕？", ["烤箱预热"]),
    ("巴黎在哪个国家？", ["法兰西共和国"]),
    ("量子计算是什么？", ["量子比特纠缠"]),
    ("养猫需要注意什么？", ["猫粮配比"]),
]


def main() -> None:
    noise = os.getenv("EVAL_NOISE") == "1"
    qa = NOISE_QA + QA[5:] if noise else QA

    db_path = config.DB_PATH
    if os.path.exists(db_path):
        os.remove(db_path)
    db.init_db()
    conn = db.connect()
    conn.execute("DELETE FROM docs WHERE tenant_id=?", (TENANT,))
    conn.commit()

    print(f"评估库：{db_path}")
    print(f"入库文档：{len(DOCS)} 份；问答：{len(qa)} 条；模式：{'反向(无关问句)' if noise else '正常'}")
    for d in DOCS:
        rag.add_document(TENANT, d["title"], d["text"], "synthetic")

    hits = 0
    rows = []
    for q, kws in qa:
        res = rag.search(TENANT, q, top_k=3)
        found = any(any(kw in r["text"] for kw in kws) for r in res)
        if found:
            hits += 1
        rows.append((q, " / ".join(kws), len(res), found))

    rate = hits / len(qa) * 100
    print(f"Top-3 命中率={rate:.2f}%")

    # 写报告
    report = os.path.join("data", "eval_report.md")
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        f"# MiniYuxi 检索命中率测评报告",
        f"",
        f"- 生成时间：{now}",
        f"- 检索模式：{'反向验证（前5条改为无关问句）' if noise else '正常测评'}",
        f"- 入库文档数：{len(DOCS)} 份（合成 HR 制度，离线 BM25）",
        f"- 问答条数：{len(qa)} 条",
        f"- **Top-3 命中率：{rate:.2f}%**（命中 {hits}/{len(qa)}）",
        f"",
        f"## 逐条明细",
        f"",
        f"| # | 问题 | 期望关键词 | 命中片段数 | 是否命中 |",
        f"|---|------|-----------|-----------|----------|",
    ]
    for i, (q, kw, n, ok) in enumerate(rows, 1):
        lines.append(f"| {i} | {q} | {kw} | {n} | {'✅' if ok else '❌'} |")
    lines += [
        "",
        "## 说明",
        "- 命中定义：对每条问题取 Top-3 检索片段，若任一片段原文包含任一期望关键词，记为命中。",
        "- 本测评直接调用 `core.rag.search`，未改动任何检索实现（防作弊）。",
        "- 反向验证（EVAL_NOISE=1）将前 5 条问题替换为与制度无关的问句，命中率应明显下降。",
        "- 基线自记：正常模式命中率为本文件对应数值；后续改动只许升不许降（功能取舍以引用优先）。",
        "",
    ]
    with open(report, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"报告已写入：{report}")


if __name__ == "__main__":
    main()
